#!/usr/bin/env node
// Generates the synthetic price series used as the signin-page backdrop.
// Model: geometric Brownian walk with normally distributed log returns.
//   r_t  ~ N(drift, vol^2)
//   p_t  = p_{t-1} * exp(r_t)
// Seeded mulberry32 RNG + Box-Muller transform for determinism.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const SEED = Number(process.argv[2]) || Date.now();
const COUNT = 96;
const START = 100;
const DRIFT = 0.005;
const VOL = 0.045;

function mulberry32(seed) {
	let a = seed >>> 0;
	return function () {
		a = (a + 0x6d2b79f5) >>> 0;
		let t = a;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

function gaussian(rng) {
	let u = 0;
	let v = 0;
	while (u === 0) u = rng();
	while (v === 0) v = rng();
	return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

function generate() {
	const rng = mulberry32(SEED);
	const prices = [START];
	for (let i = 1; i < COUNT; i++) {
		const r = DRIFT + VOL * gaussian(rng);
		prices.push(prices[i - 1] * Math.exp(r));
	}
	return prices.map((p) => Number(p.toFixed(4)));
}

const series = generate();
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../src/lib/data/signinTrail.ts');

const body = `// Generated by scripts/gen-signin-trail.mjs. Do not edit by hand.
export const signinTrail: number[] = ${JSON.stringify(series, null, 2)};
`;

writeFileSync(out, body);
console.log(`wrote ${out} (${series.length} points, seed=${SEED})`);
